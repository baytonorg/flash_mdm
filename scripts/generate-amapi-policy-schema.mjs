import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const DISCOVERY_URL = 'https://androidmanagement.googleapis.com/$discovery/rest?version=v1';
const DEFAULT_OUTPUT = 'netlify/functions/_lib/amapi-policy-discovery-schema.ts';

function parseArgs(args) {
  const options = { check: false, input: null, output: DEFAULT_OUTPUT };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--check') options.check = true;
    else if (arg === '--input') options.input = args[++index];
    else if (arg === '--output') options.output = args[++index];
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

async function loadDiscovery(input) {
  if (input) return JSON.parse(await readFile(resolve(input), 'utf8'));
  const response = await fetch(DISCOVERY_URL);
  if (!response.ok) throw new Error(`Failed to fetch AMAPI Discovery: HTTP ${response.status}`);
  return response.json();
}

function shrinkDescriptor(value) {
  const descriptor = {};
  for (const key of ['$ref', 'type', 'format', 'enum']) {
    if (value[key] !== undefined) descriptor[key] = value[key];
  }
  if (value.items) descriptor.items = shrinkDescriptor(value.items);
  if (value.additionalProperties) descriptor.additionalProperties = shrinkDescriptor(value.additionalProperties);
  if (value.properties) {
    descriptor.properties = Object.fromEntries(
      Object.entries(value.properties)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, child]) => [key, shrinkDescriptor(child)])
    );
  }
  return descriptor;
}

function buildPinnedSchema(discovery) {
  if (discovery.id !== 'androidmanagement:v1' || !discovery.schemas?.Policy) {
    throw new Error('Input is not the Android Management API v1 Discovery document');
  }
  if (!/^\d{8}$/.test(discovery.revision ?? '')) {
    throw new Error(`Unexpected AMAPI Discovery revision: ${discovery.revision ?? '<missing>'}`);
  }

  const reachable = new Set(['Policy']);
  const visit = (descriptor) => {
    if (!descriptor || typeof descriptor !== 'object') return;
    if (descriptor.$ref && !reachable.has(descriptor.$ref)) {
      if (!discovery.schemas[descriptor.$ref]) {
        throw new Error(`Missing referenced Discovery schema: ${descriptor.$ref}`);
      }
      reachable.add(descriptor.$ref);
      visit(discovery.schemas[descriptor.$ref]);
    }
    visit(descriptor.items);
    visit(descriptor.additionalProperties);
    Object.values(descriptor.properties ?? {}).forEach(visit);
  };
  visit(discovery.schemas.Policy);

  return {
    source: DISCOVERY_URL,
    revision: discovery.revision,
    root: 'Policy',
    schemas: Object.fromEntries(
      [...reachable]
        .sort((left, right) => left.localeCompare(right))
        .map((name) => [name, shrinkDescriptor(discovery.schemas[name])])
    ),
  };
}

function renderModule(schema) {
  return `// Generated by scripts/generate-amapi-policy-schema.mjs. Do not edit manually.\n`
    + `// Refresh deliberately with \`npm run amapi-schema:update\` and review the schema diff.\n`
    + `export const AMAPI_POLICY_DISCOVERY_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n`;
}

const options = parseArgs(process.argv.slice(2));
const outputPath = resolve(options.output);
const rendered = renderModule(buildPinnedSchema(await loadDiscovery(options.input)));

if (options.check) {
  const existing = await readFile(outputPath, 'utf8');
  if (existing !== rendered) {
    throw new Error(`${options.output} is not aligned with the current AMAPI Discovery document`);
  }
  console.log(`AMAPI policy schema is current (${options.output})`);
} else {
  await writeFile(outputPath, rendered);
  console.log(`Updated ${options.output}`);
}
